/**
 * gen-headers.mjs — writes dist/_headers after `astro build`.
 *
 * Workers Static Assets applies this file to every static response (it is not served itself),
 * and server.mjs reads the same file, so both hosts send identical headers:
 *   - security headers on every page, including a Content-Security-Policy whose script-src lists
 *     a sha256 hash for each inline script Astro emitted, so no 'unsafe-inline' is needed;
 *   - long-lived caching for fingerprinted /_astro/ files, a day for other static files.
 * Run automatically by `npm run build`.
 */
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, extname, resolve } from 'node:path';
import { createHash } from 'node:crypto';

const DIST = resolve(process.cwd(), 'dist');
if (!existsSync(DIST)) { console.error('gen-headers: dist/ not found — run astro build first'); process.exit(1); }

const walk = (d) => readdirSync(d).flatMap((f) => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
const pages = walk(DIST).filter((f) => extname(f) === '.html');

/* Everything is derived from the built HTML, so the policy always matches what was built,
   whatever environment variables the build saw. */
const hashes = new Set();
const scriptOrigins = new Set();
const endpointOrigins = new Set();
const origin = (u) => { try { return new URL(u).origin; } catch { return null; } };
for (const file of pages) {
  const html = readFileSync(file, 'utf8');
  for (const [, attrs, body] of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
    const src = /\bsrc\s*=\s*["']([^"']+)/i.exec(attrs)?.[1];
    if (src) { if (/^https?:\/\//.test(src)) scriptOrigins.add(origin(src)); continue; }
    // Inline, executable scripts only: JSON-LD and other data blocks never run.
    const type = /\btype\s*=\s*["']?([^"'\s>]+)/i.exec(attrs)?.[1]?.toLowerCase() ?? '';
    if (type && !['module', 'text/javascript', 'application/javascript'].includes(type)) continue;
    if (!body.trim()) continue;
    hashes.add(`'sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}'`);
  }
  // A contact endpoint on another origin (PUBLIC_CONTACT_ENDPOINT) must be reachable by fetch and form posts.
  for (const [, url] of html.matchAll(/\b(?:data-endpoint|action)\s*=\s*["'](https?:\/\/[^"']+)/gi)) endpointOrigins.add(origin(url));
}
scriptOrigins.delete(null);
endpointOrigins.delete(null);

/* Turnstile loads its script from, and renders its iframe on, this origin (contact page). */
const TURNSTILE = 'https://challenges.cloudflare.com';

const csp = [
  "default-src 'self'",
  ['script-src', "'self'", ...[...hashes].sort(), TURNSTILE, ...scriptOrigins].join(' '),
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self' data:", // small font subsets are inlined into the CSS as data: URLs by the build
  ['connect-src', "'self'", ...endpointOrigins, ...scriptOrigins].join(' '),
  `frame-src ${TURNSTILE}`,
  "object-src 'none'",
  "base-uri 'self'",
  ['form-action', "'self'", ...endpointOrigins].join(' '),
  "frame-ancestors 'none'",
  'upgrade-insecure-requests',
].join('; ');

// The _headers format caps a line at 2,000 characters; fail loudly rather than ship a cut policy.
if (csp.length > 1900) {
  console.error(`gen-headers: Content-Security-Policy is ${csp.length} characters (limit ~2000). Move inline scripts into bundled files.`);
  process.exit(1);
}

const rules = `# Generated by scripts/gen-headers.mjs during the build. Do not edit by hand.
/*
  Strict-Transport-Security: max-age=31536000
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()
  Cross-Origin-Opener-Policy: same-origin

/_astro/*
  Cache-Control: public, max-age=31536000, immutable

/brand/*
  Cache-Control: public, max-age=86400

/og/*
  Cache-Control: public, max-age=86400

/favicon.ico
  Cache-Control: public, max-age=86400

/favicon.png
  Cache-Control: public, max-age=86400

/favicon-32.png
  Cache-Control: public, max-age=86400

/apple-touch-icon.png
  Cache-Control: public, max-age=86400
`;

writeFileSync(join(DIST, '_headers'), rules);
console.log(`gen-headers: wrote dist/_headers — ${hashes.size} inline script hash(es), CSP ${csp.length} chars.`);
